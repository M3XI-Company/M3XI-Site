/*
 * m3xi.com — the team pages, from one template.
 *
 *   node tools/build-team.mjs
 *
 * Reads team/people.json and writes /team/ (the directory) and one profile per
 * person: team/<slug>/index.html, or the person's `out` (Michael keeps
 * /michael/). Every profile has the same parts in the same order: portrait and
 * facts, role, about, focus, selected work, contact. vite.config.js finds
 * team/<slug>/ pages by itself.
 *
 * A portrait is public/team-photos/<slug>.jpg (or the person's `photo`); with
 * no file there, the card shows initials.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { header, footer } from "./site-chrome.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const data = JSON.parse(readFileSync(resolve(root, "team/people.json"), "utf8"));
const people = data.people;
const bySlug = Object.fromEntries(people.map((p) => [p.slug, p]));

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&rsquo;");
const urlOf = (p) => p.url || `/team/${p.slug}/`;
const first = (p) => p.name.split(" ")[0];
const initials = (p) => p.name.split(/\s+/).map((w) => w.replace(/^O'/i, "O")[0]).join("").slice(0, 2).toUpperCase();

function photoOf(p) {
  const path = p.photo || `/team-photos/${p.slug}.jpg`;
  return existsSync(resolve(root, "public", "." + path)) ? path : null;
}

function portrait(p, { size, eager } = {}) {
  const src = photoOf(p);
  const inner = src
    ? `<img src="${src}" alt="${esc(p.name)}" width="800" height="1000"${eager ? "" : ' loading="lazy"'} decoding="async"${size ? ` sizes="${size}"` : ""}>`
    : `<span class="co-photo-mono" aria-hidden="true">${esc(initials(p))}</span>`;
  return `<div class="co-photo">${inner}</div>`;
}

