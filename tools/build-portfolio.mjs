/* ── a plate ─────────────────────────────────────────────────────────────── */

let plateNo = 0;
function plate(p) {
  plateNo += 1;
  const no = String(plateNo).padStart(2, "0");
  const cls = ["bk-plate", "s" + (p.span || 2), p.ratio ? "r-" + p.ratio : ""].filter(Boolean).join(" ");
  const cap = `<figcaption class="bk-cap"><b>${esc(p.title)}</b><span>${esc(p.text)}</span></figcaption>`;
  const tag = `<span class="bk-tag">${no}</span>`;
  const pos = p.pos ? ` style="object-position:${p.pos}"` : "";
  let inner;
  if (p.yt) {
    inner = `<button type="button" class="bk-shot bk-video" data-yt="${p.yt}" data-start="${p.start || 0}" aria-label="Play: ${esc(p.title)}"><img src="${A}${p.img}" alt="${esc(p.alt)}" loading="lazy" decoding="async"><span class="bk-play">Play film</span></button>`;
  } else if (p.type) {
    const tagName = p.href ? "a" : "div";
    const extra = p.kind === "network" ? '<canvas data-network="dark" aria-hidden="true"></canvas>'
      : p.kind === "magnet" ? '<canvas data-magnet aria-label="Particles drawn towards a moving magnet"></canvas>'
      : (p.logo ? `<img class="bk-logo" src="${p.logo}" alt="" loading="lazy" decoding="async">` : "") + (p.screen ? `<img class="bk-screen" src="${p.screen}" alt="" loading="lazy" decoding="async">` : "");
    inner = `<${tagName} class="bk-shot bk-type${p.tone ? " bk-type--" + p.tone : ""}"${p.href ? ` href="${p.href}"` : ' tabindex="0"'}>${extra}<strong>${esc(p.type)}</strong><em>${esc(p.label)}</em></${tagName}>`;
  } else {
    inner = `<button type="button" class="bk-shot" data-large="${A}${p.img}" aria-label="View large: ${esc(p.title)}"><img src="${A}${p.img}" alt="${esc(p.alt)}" loading="lazy" decoding="async"${pos}></button>`;
  }
  return `      <figure class="${cls}">${tag}${inner}${cap}</figure>`;
}

function chapter(c, i) {
  return `<section class="bk-chapter" aria-labelledby="ch-${i}"><div class="co-wrap">
  <div class="bk-chapter-head"><span class="bk-no">${String(i + 1).padStart(2, "0")}</span><h2 id="ch-${i}">${esc(c.title)}</h2><i aria-hidden="true"></i><small>${esc(c.note)}</small></div>
  <div class="bk-grid">
${c.plates.map(plate).join("\n")}
  </div>
</div></section>`;
}

