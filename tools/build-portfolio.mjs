/*
 * m3xi.com/michael/portfolio/ — Michael's booklets and CV, from one template.
 *
 *   node tools/build-portfolio.mjs
 *
 * Writes three pages, all with the site's header and footer and the brand's
 * white, black and blue (shared/company.css + shared/book.css):
 *
 *   michael/portfolio/index.html         Modelling x Performance: the model book
 *   michael/portfolio/engineering.html   Engineering: the same booklet, of work
 *   michael/portfolio/cv.html            Work CV and Performance CV
 *
 * A booklet is chapters of plates. A plate is one of:
 *   { img, title, text, alt }                 a photograph (opens large)
 *   { yt, start, img, title, text, alt }      a film: the still, then the player
 *   { type, kind, title, text, href?, ... }   type or something live, where there is no photograph yet
 * plus `span` (2, 3, 4 or 6 of six columns) and `ratio` ('tall' 4:5, 'wide' 16:9, 'band' 3:1, 'fill').
 * `title` and `text` are the caption that comes up when the plate is hovered.
 *
 * Photographs live in public/michael/portfolio/assets/. To add one, drop the
 * file there and add a plate below. The PDFs are public/michael/portfolio/
 * work-cv.pdf and cv.pdf (the performance CV).
 */
